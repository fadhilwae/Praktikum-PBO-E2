    public void tampilkanSemuaMhs() {
        List<Mahasiswa> listmhs = mhsService.getAll();
        
        dlmId.clear();
        dlmNama.clear();
        
        for (Mahasiswa mahasiswa : listmhs) {
            addId(mahasiswa.getId());
            addNama(mahasiswa.getNama());
        }
    }

