    private void jButtonTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTambahActionPerformed
        String nama = jTextFieldNama.getText();

        Mahasiswa mhs = new Mahasiswa();
        mhs.setNama(nama);
        
        mhsService.add(mhs);
        tampilkanSemuaMhs();

        jTextFieldNama.setText("");
    }//GEN-LAST:event_jButtonTambahActionPerformed

    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        int id = Integer.parseInt(jTextFieldEditId.getText());
        String nama = jTextFieldEditNama.getText();
        
        Mahasiswa mhs = new Mahasiswa(id, nama);
        mhsService.update(mhs);
        tampilkanSemuaMhs();
        
        jTextFieldEditId.setText("");
        jTextFieldEditNama.setText("");
        
        jTextFieldHapusId.setText("");
        jTextFieldHapusNama.setText("");
    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jListIdValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jListIdValueChanged
        String id = jListId.getSelectedValue();
        if(id == null || id.isEmpty()) {
            return;
        }

        Mahasiswa mhs = mhsService.getById(Integer.parseInt(id));
        
        jTextFieldEditId.setText(String.valueOf(mhs.getId()));
        jTextFieldEditNama.setText(mhs.getNama());
        
        jTextFieldHapusId.setText(String.valueOf(mhs.getId()));
        jTextFieldHapusNama.setText(mhs.getNama());
    }//GEN-LAST:event_jListIdValueChanged

    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
        int id = Integer.parseInt(jTextFieldHapusId.getText());
        
        mhsService.delete(id);
        tampilkanSemuaMhs();
        
        jTextFieldEditId.setText("");
        jTextFieldEditNama.setText("");
        
        jTextFieldHapusId.setText("");
        jTextFieldHapusNama.setText("");
    }//GEN-LAST:event_jButtonHapusActionPerformed

    private void jButtonResetIndeksActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonResetIndeksActionPerformed
        if(mhsService.isEmpty()) {
            mhsService.indexReset();
        } else {
            System.out.println("Tabel tidak kosong");
        }
    }//GEN-LAST:event_jButtonResetIndeksActionPerformed

