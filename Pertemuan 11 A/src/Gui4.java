    private void tombol_savetolistActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_savetolistActionPerformed
        // TODO add your handling code here:
        itemList.clear();
        
        for (int i = 0; i < dlm.getSize(); i++) {
            itemList.add(dlm.getElementAt(i));
        }
        
        data_tersimpan_list.setText("Data Tersimpan = " + itemList.size());
    }//GEN-LAST:event_tombol_savetolistActionPerformed

    private void tombol_updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_updateActionPerformed
        // TODO add your handling code here:
        int index = list_item.getSelectedIndex();
        String selected = teks_nama_item.getText().trim();
    
        if (index != -1 && !selected.isEmpty()) {
            dlm.setElementAt(selected, index);
            teks_nama_item.setText("");
        }
    }//GEN-LAST:event_tombol_updateActionPerformed

    private void tombol_addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_addActionPerformed
        // TODO add your handling code here:
        String namaItem = teks_nama_item.getText().trim();
    
        if (!namaItem.isEmpty()) {
            dlm.addElement(namaItem); // Langsung masukkan ke model
            teks_nama_item.setText(""); // Kosongkan textfield
        }
    }//GEN-LAST:event_tombol_addActionPerformed

    private void tombol_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_deleteActionPerformed
        // TODO add your handling code here:
        int index = list_item.getSelectedIndex();
    
        if (index != -1) {
            dlm.removeElementAt(index);
            teks_nama_item.setText("");
        }
    }//GEN-LAST:event_tombol_deleteActionPerformed

