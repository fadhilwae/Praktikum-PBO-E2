    private void tombol_insertdatalistActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_insertdatalistActionPerformed
        // TODO add your handling code here:
        dlm.clear(); // Bersihkan JList terlebih dahulu
        
        for (String item : itemList) {
            dlm.addElement(item);
        }
    }//GEN-LAST:event_tombol_insertdatalistActionPerformed

    private void tombol_savetosetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_savetosetActionPerformed
        // TODO add your handling code here:
        itemSet.clear();
        
        for (int i = 0; i < dlm.getSize(); i++) {
            itemSet.add(dlm.getElementAt(i));
        }
        
        data_tersimpan_set.setText("Data Tersimpan = " + itemSet.size());
    }//GEN-LAST:event_tombol_savetosetActionPerformed

    private void tombol_insertdatasetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_insertdatasetActionPerformed
        // TODO add your handling code here:
        dlm.clear();
        
        for (String item : itemSet) {
            dlm.addElement(item);
        }
    }//GEN-LAST:event_tombol_insertdatasetActionPerformed

    private void tombol_savetomapActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_savetomapActionPerformed
        // TODO add your handling code here:
        itemMap.clear(); // Bersihkan data lama
    
        for (int i = 0; i < dlm.getSize(); i++) {
            itemMap.put(i, dlm.getElementAt(i)); // i sebagai key, nama item sebagai value
        }
    
        data_tersimpan_map.setText("Data Tersimpan = " + itemMap.size());
    }//GEN-LAST:event_tombol_savetomapActionPerformed

    private void tombol_insertdatamapActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tombol_insertdatamapActionPerformed
        // TODO add your handling code here:
        dlm.clear();
    
        for (java.util.Map.Entry<Integer, String> entry : itemMap.entrySet()) {
            dlm.addElement(entry.getValue());
        }
    }//GEN-LAST:event_tombol_insertdatamapActionPerformed

